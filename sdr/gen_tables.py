#!/usr/bin/env python3
"""ROM tables for the SDR display -> tables.v
  font_rom   8x8 glyphs ASCII 32..95 (Linux console VGA8 font)
  meter_rom  40-char S-meter scale labels (1x), positions match sdr_top's
             bar: x = 16 + (dBm + 127) * 288/114, S1 = -121 dBm, 6 dB/S
  scale_rom  40-char kHz offsets under the spectrum (1x)
  fft_win.hex, fft_tw.hex  fft512 window / twiddle ROMs
"""
import gzip, math, os
HERE = os.path.dirname(os.path.abspath(__file__))
out = []
def rom(name, in_w, out_w, items, comment):
    out.append(f"// {comment}")
    out.append(f"module {name} (input wire [{in_w-1}:0] a, output wire [{out_w-1}:0] d);")
    out.append(f"    function [{out_w-1}:0] f(input [{in_w-1}:0] v);")
    out.append("        case (v)")
    for k, v in items:
        out.append(f"            {in_w}'d{k}: f = {out_w}'h{v:x};")
    out.append(f"            default: f = {out_w}'h0;")
    out.append("        endcase")
    out.append("    endfunction")
    out.append("    assign d = f(a);")
    out.append("endmodule\n")

d = gzip.open("/usr/share/consolefonts/Lat15-VGA8.psf.gz").read()
assert d[0] == 0x36 and d[3] == 8
rom("font_rom", 9, 8, [((c - 32) << 3 | r, d[4 + c * 8 + r]) for c in range(32, 96) for r in range(8)],
    "a = {char-32, row} -> 8 pixels, MSB left")

def text(name, w, s, comment):
    assert len(s) <= 1 << w, (name, len(s))
    s = s.ljust(1 << w)
    rom(name, w, 6, [(i, ord(ch) - 32) for i, ch in enumerate(s)], comment + f': "{s.rstrip()}"')

# S-meter labels: char index = round(x/8) of the tick
lab = [" "] * 40
def put(x, s):
    c = round(x / 8 - (len(s) - 1) / 2)
    for i, ch in enumerate(s):
        lab[c + i] = ch
for su in (1, 3, 5, 7, 9):
    put(16 + (-121 + 6 * (su - 1) + 127) * 288 / 114, str(su))
for over in (20, 40, 60):
    put(16 + (-73 + over + 127) * 288 / 114, "+" + str(over))
lab[0] = "S"
text("meter_rom", 6, "".join(lab), "S-meter scale")
# kHz offsets under the spectrum: ticks every 5 kHz = 48.55 px from x = 160
lab = [" "] * 40
for k, s_ in zip(range(-3, 4), ("-15", "-10", "-5", "0", "+5", "+10", "+15")):
    put(160 + k * 5000 / (64.8e6 / 1229 / 512), s_)
scale_n = "".join(lab)
print("scale:", scale_n)
# wide span (+-33 kHz, 205.96 Hz/bin): ticks every 10 kHz at the same pixels
lab = [" "] * 40
for k, s_ in zip(range(-3, 4), ("-30", "-20", "-10", "0", "+10", "+20", "+30")):
    put(160 + k * 10000 / (64.8e6 / 614 / 512), s_)
print("scale2:", "".join(lab))
# one ROM, a = {wide, char}: avoids a mux level in the pixel path (Fmax)
text("scale_rom", 7, scale_n.ljust(64) + "".join(lab), "kHz scales under the spectrum (narrow | wide)")
# FFT tables for fft512.v: Blackman-Harris window (Q15) and twiddles
# W^k = exp(-j 2 pi k/512), k = 0..255, {cos, -sin} as Q14 signed 16-bit.
N = 512
a = (0.35875, 0.48829, 0.14128, 0.01168)
with open(os.path.join(HERE, "fft_win.hex"), "w") as fw:
    for i in range(N):
        t = 2 * math.pi * (i + 0.5) / N
        w = a[0] - a[1] * math.cos(t) + a[2] * math.cos(2 * t) - a[3] * math.cos(3 * t)
        fw.write(f"{min(32767, round(w * 32767)):04x}\n")
with open(os.path.join(HERE, "fft_tw.hex"), "w") as fw:
    for k in range(N // 2):
        c = round(16384 * math.cos(2 * math.pi * k / N)) & 0xFFFF
        sn = round(-16384 * math.sin(2 * math.pi * k / N)) & 0xFFFF
        fw.write(f"{c:04x}{sn:04x}\n")
open(os.path.join(HERE, "tables.v"), "w").write("// GENERATED by gen_tables.py\n" + "\n".join(out))
