#!/usr/bin/env python3
"""Generates main/font.h: fixed-cell 1bpp bitmap fonts (ASCII 32..126) rendered
from DejaVu Sans Mono. Run from esp32/:  python3 tools/gen_font.py
Each glyph is h rows; each row is ceil(w/8) bytes, MSB = leftmost pixel."""
from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
FONTS = [  # name, ttf, size, cell w, cell h
    # sized for the 480x320 display
    ("font_small", TTF, 12, 7, 14),
    ("font_mid", TTF, 16, 10, 19),
    ("font_big", BOLD, 34, 21, 36),
]

def render(ttf, size, w, h):
    f = ImageFont.truetype(ttf, size)
    asc, desc = f.getmetrics()
    top = (h - (asc + desc)) // 2
    out = []
    for c in range(32, 127):
        im = Image.new("1", (w, h), 0)
        d = ImageDraw.Draw(im)
        bw = f.getlength(chr(c))
        d.text(((w - bw) / 2, top), chr(c), font=f, fill=1)
        bpr = (w + 7) // 8
        for y in range(h):
            for b in range(bpr):
                v = 0
                for bit in range(8):
                    x = b * 8 + bit
                    if x < w and im.getpixel((x, y)):
                        v |= 0x80 >> bit
                out.append(v)
    return out

with open("main/font.h", "w") as o:
    o.write("// Generated by tools/gen_font.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    o.write("typedef struct { uint8_t w, h; const uint8_t *bits; } font_t;\n\n")
    for name, ttf, size, w, h in FONTS:
        data = render(ttf, size, w, h)
        o.write(f"static const uint8_t {name}_bits[] = {{\n")
        for i in range(0, len(data), 16):
            o.write("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ",\n")
        o.write("};\n")
        o.write(f"static const font_t {name} = {{ {w}, {h}, {name}_bits }};\n\n")
